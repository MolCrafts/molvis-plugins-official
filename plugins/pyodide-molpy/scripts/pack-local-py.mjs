#!/usr/bin/env node
/**
 * Pack monorepo pure-Python packages for the Pyodide plugin runtime.
 *
 * Sources (sibling checkouts relative to this repo):
 *   ../../../molvis/python/src/molvis  → molvis/*
 *   ../../../molpy/src/molpy           → molpy/*
 *
 * Writes `src/kernel/local_py_sources.ts` (consumed by install_runtime.ts).
 * That file is **committed** so CI can build without monorepo siblings.
 * When siblings are present, re-run this script (prebuild/pretest) to refresh.
 *
 * Skips dist/, __pycache__, *.pyc, tests, large non-python assets.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const pluginRoot = path.resolve(__dirname, "..");
const outFile = path.join(pluginRoot, "src/kernel/local_py_sources.ts");

const SKIP_DIRS = new Set([
  "dist",
  "__pycache__",
  ".git",
  "tests",
  "node_modules",
  ".tox",
  ".venv",
]);

/** @type {Record<string, string>} */
const files = {};

/**
 * @param {string} dir
 * @param {string} prefix  path prefix inside the package (e.g. "molvis")
 */
function walk(dir, prefix) {
  for (const name of fs.readdirSync(dir)) {
    if (SKIP_DIRS.has(name)) continue;
    if (name.endsWith(".pyc") || name.endsWith(".pyo")) continue;
    const full = path.join(dir, name);
    const rel = `${prefix}/${name}`;
    const st = fs.statSync(full);
    if (st.isDirectory()) {
      walk(full, rel);
    } else if (name.endsWith(".py")) {
      files[rel] = fs.readFileSync(full, "utf8");
    } else if (
      // keep small package data (ff xml etc.) under molpy/data
      (name.endsWith(".xml") ||
        name.endsWith(".ff") ||
        name.endsWith(".json") ||
        name.endsWith(".lark")) &&
      prefix.includes("/data")
    ) {
      files[rel] = fs.readFileSync(full, "utf8");
    } else if (name.endsWith(".lark") && prefix.includes("parser")) {
      files[rel] = fs.readFileSync(full, "utf8");
    }
  }
}

const molvisSrc = path.resolve(
  pluginRoot,
  "../../../molvis/python/src/molvis",
);
const molpySrc = path.resolve(pluginRoot, "../../../molpy/src/molpy");

const haveMolvis = fs.existsSync(molvisSrc);
const haveMolpy = fs.existsSync(molpySrc);

if (!haveMolvis || !haveMolpy) {
  const missing = [
    !haveMolvis ? molvisSrc : null,
    !haveMolpy ? molpySrc : null,
  ].filter(Boolean);
  if (fs.existsSync(outFile)) {
    console.warn(
      `pack-local-py: monorepo sources missing (${missing.join(", ")}); keeping committed ${path.relative(pluginRoot, outFile)}`,
    );
    process.exit(0);
  }
  console.error(
    `pack-local-py: monorepo sources missing and no committed pack at ${path.relative(pluginRoot, outFile)}`,
  );
  for (const m of missing) console.error(`  missing: ${m}`);
  process.exit(1);
}

walk(molvisSrc, "molvis");
walk(molpySrc, "molpy");

const keys = Object.keys(files).sort();
const body = keys
  .map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(files[k])},`)
  .join("\n");

const banner = `/* AUTO-GENERATED by scripts/pack-local-py.mjs — do not edit by hand */
/* ${keys.length} modules: monorepo molvis + molpy */
/* Refresh when sibling molvis/molpy trees change; commit for CI. */

export const LOCAL_PY_SOURCES: Record<string, string> = {
${body}
};

/** Root on Pyodide FS; packages live at ROOT/molvis, ROOT/molpy */
export const LOCAL_PY_ROOT = "/home/pyodide/packages";
`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, banner);

const nMolvis = keys.filter((k) => k.startsWith("molvis/")).length;
const nMolpy = keys.filter((k) => k.startsWith("molpy/")).length;
console.log(
  `Wrote ${keys.length} modules (molvis=${nMolvis}, molpy=${nMolpy}) → ${path.relative(pluginRoot, outFile)}`,
);
